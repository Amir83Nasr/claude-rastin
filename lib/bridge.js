'use strict';

// ── SETTINGS BRIDGE ────────────────────────────────────────────────────

// Neither preview surface can read VS Code settings: the built-in Markdown
// preview loads static contributions, and the Office Viewer page is served
// from its own extension. Rastin writes the two values they need to a
// generated script on activation, and both installers read the same global.
// Only the switch that turns a surface off differs.

/**
 * Normalize the bridge values for one surface.
 * @param {{enabled?: boolean, direction?: string}} values rastin.* settings
 * @param {boolean|undefined} surface the setting that disables this surface
 * @returns {{enabled: boolean, direction: 'auto'|'rtl'|'ltr'}}
 */
function values({ enabled, direction }, surface) {
  return {
    enabled: enabled !== false && surface !== false,
    direction: direction === 'rtl' || direction === 'ltr' ? direction : 'auto',
  };
}

/**
 * The generated script. Written in Prettier's shape on purpose.
 * @param {{enabled: boolean, direction: string}} values normalized settings
 * @param {string} [name] global the surface's installer reads
 */
function script({ enabled, direction }, name = '__rastinPreview') {
  return (
    '/* Generated by Rastin on activation; do not edit. */\n' +
    `globalThis.${name} = { enabled: ${enabled}, direction: '${direction}' };\n`
  );
}

module.exports = { values, script };
